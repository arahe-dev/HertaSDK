package main

import (
	"bytes"
	"encoding/json"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

func TestScan(t *testing.T) {
	root := t.TempDir()
	git := func(args ...string) {
		t.Helper()
		cmd := exec.Command("git", args...)
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v: %s", args, err, out)
		}
	}
	write := func(path, content string) {
		t.Helper()
		f := filepath.Join(root, path)
		if err := os.MkdirAll(filepath.Dir(f), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(f, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	const src = `package example
import "github.com/hashicorp/go-retryablehttp"
func send() { retryablehttp.Post(path, typ, body) }
`
	git("init", "--quiet")
	write("examples/client.go", "//go:build windows\n\n"+src)
	write("fake_test.go", src)
	write("testdata/fake.go", "not valid Go")
	write("generated.go", "// Code generated by the test. DO NOT EDIT.\n\n"+src)
	write("sparse.go", src)
	git("add", ".")
	git("update-index", "--skip-worktree", "sparse.go")
	if err := os.Remove(filepath.Join(root, "sparse.go")); err != nil {
		t.Fatal(err)
	}
	write("untracked.go", src)

	var buf bytes.Buffer
	if err := scan(root, &buf); err != nil {
		t.Fatal(err)
	}
	var got report
	if err := json.Unmarshal(buf.Bytes(), &got); err != nil {
		t.Fatal(err)
	}
	if got.Files != 1 || got.SparseOmitted != 1 || len(got.Findings) != 1 ||
		got.Findings[0].Path != "examples/client.go" ||
		got.Findings[0].Rule != "RK002" {
		t.Errorf("unexpected scan: %s", &buf)
	}
}
