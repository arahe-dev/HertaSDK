#!/usr/bin/env bash
# Regenerates per-implementation adapters from orig.go.
# Usage: bash lab/impl/gen.sh
set -euo pipefail
cd "$(dirname "$0")"

gen() { # $1=name  $2=import path  $3=doc sentence
  {
    printf '%s\n\n' '// Code generated by gen.sh from orig.go; DO NOT EDIT.'
    sed -e "s#h \"github.com/arahe-dev/hertasdk/lab/v02\"#h \"$2\"#" \
        -e "s/\borigImpl\b/${1}Impl/g; s/\borigRuntime\b/${1}Runtime/g" \
        -e "s/^var Orig Impl/var ${1^} Impl/; s#^// Orig is .*#// ${1^} is $3#" \
        -e "s/return \"orig\"/return \"$1\"/" \
        orig.go
  } > "$1.go"
  gofmt -w "$1.go"
}

# recon is the name the lab has always used for the reconstruction; since
# v1.0-next it is the root package itself.
gen recon "github.com/arahe-dev/hertasdk" "the root package, hertasdk (v1.0-next): the first-principles reconstruction."
